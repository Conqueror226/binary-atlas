import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const base=new URL('../site/',import.meta.url);
const data=fs.readFileSync(new URL('data.js',base),'utf8');
const app=fs.readFileSync(new URL('app.js',base),'utf8');
const context=vm.createContext({localStorage:{getItem:()=>null,setItem:()=>{}},setTimeout,clearTimeout,console});
vm.runInContext(data+app.slice(0,app.indexOf("$('#nav').innerHTML")),context);
const run=s=>vm.runInContext(s,context);
assert.equal(run('initial().notes.length'),0);
assert.equal(run('initial().portfolio.length'),0);
assert.equal(run('validateState({schema:1}).env.c'),'Unknown / not assessed');
assert.equal(run('validateState({schema:1,portfolio:[{title:"Draft",status:"self-verified"}]}).portfolio[0].status'),'draft');
assert.throws(()=>run('validateState({schema:2})'));
assert.throws(()=>run('validateState({schema:1,notes:"invalid"})'));
assert.equal(run('validateState({schema:1,sessions:[{minutes:-20,lab:"missing"}]}).sessions[0].minutes'),1);
assert.equal(run('validateState({schema:1,sessions:[{lab:"missing"}]}).sessions[0].lab'),'readiness');
assert.equal(run('validateState({schema:1,bookmarks:["fake","ghidra"]}).bookmarks.join(",")'),'ghidra');
assert.equal(run('JSON.stringify(validateState(JSON.parse(JSON.stringify(initial()))))'),run('JSON.stringify(validateState(initial()))'));
run('const fixture=initial(); fixture.notes.push({id:"n1",title:"Question <A>",body:"Observation & uncertainty",tag:"Research",updated:"2026-11-11"}); fixture.completions.branch={date:"2026-11-11",evidence:"Own build report"};');
assert.equal(run('validateState(JSON.parse(JSON.stringify(fixture))).notes[0].body'),'Observation & uncertainty');
assert.equal(run('validateState(JSON.parse(JSON.stringify(fixture))).completions.branch.evidence'),'Own build report');
assert.equal(run('esc("<script> & \\\"x\\\"")'),'&lt;script&gt; &amp; &quot;x&quot;');
console.log('State checks passed: empty initial achievements, unknown baseline, backup round trip, invalid backup rejection, evidence gate on import, and text escaping.');
